#!/usr/bin/env python3
"""Order/scope dispatch: prove what `struct Atomic` does with its `order` and `Scope` arguments,
by comparing generated ISA instead of guessing.

Prediction derived from the source (iluvatar_platform_traits.h, baseline lines):
  load             :167-173   (void)order; (void)Scope  -> 20 combos, 1 behaviour
  store            :175-188   if (order != Relaxed) fence -> 20 combos, 2 behaviours
  6 RMW            :190-244   order unnamed, (void)Scope -> 20 combos, 1 behaviour each
  => 8 members x 5 orders x 4 scopes = 160 kernels, 9 distinct instruction sequences.

The script generates the kernels, compiles them, fingerprints each kernel body by
its mnemonic sequence, groups, and checks the grouping against the prediction.
It also dumps the IR for the RMW kernels, where the five order tags still look
different - that contrast is the point of the whole tier.
"""
import io
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get("REPO") or os.path.abspath(
    os.path.join(HERE, "..", "..", "..", ".."))
OUT = os.environ.get("OUT") or "/tmp/atomic-contract/order-scope-dispatch"
CLANG = os.environ.get("CLANG") or "/usr/local/corex/bin/clang"

MEMBERS = ["load", "store", "fetchAdd", "fetchSub", "fetchOr", "fetchAnd",
           "exchange", "compareExchange"]
ORDERS = ["Relaxed", "Acquire", "Release", "AcqRel", "SeqCst"]
SCOPES = ["System", "Device", "Block", "Thread"]

INC = [
    "-I%s/flagcx/adaptor/include/device_api" % REPO,
    "-I%s/flagcx/adaptor/include" % REPO,
    "-I%s/flagcx/include" % REPO,
    "-I%s/bindings/ir" % REPO,
    "-I%s/test/kernel/include" % REPO,
]
DEFS = ["-DUSE_ILUVATAR_ADAPTOR=1", "-DFLAGCX_ILUVATAR_DEVICE_COMPILE=1"]
BASE = ["-x", "ivcore", "--cuda-path=/usr/local/corex",
        "--cuda-gpu-arch=ivcore11", "-std=c++17", "-O2"]


def body(member, order, scope):
    """One kernel body: exactly one Atomic call, result consumed."""
    o = "(flagcxDeviceMemoryOrder_t)%d" % order
    s = "(flagcxDeviceScope_t)%d" % scope
    if member == 0:
        return ("  out[0] = A::load<unsigned, %s>(p, %s);\n" % (s, o), "out")
    if member == 1:
        return ("  A::store<unsigned, %s>(p, v, %s);\n" % (s, o), "none")
    if member == 2:
        return ("  out[0] = A::fetchAdd<unsigned, %s>(p, v, %s);\n" % (s, o), "out")
    if member == 3:
        return ("  out[0] = A::fetchSub<unsigned, %s>(p, v, %s);\n" % (s, o), "out")
    if member == 4:
        return ("  out[0] = A::fetchOr<unsigned, %s>(p, v, %s);\n" % (s, o), "out")
    if member == 5:
        return ("  out[0] = A::fetchAnd<unsigned, %s>(p, v, %s);\n" % (s, o), "out")
    if member == 6:
        return ("  out[0] = A::exchange<unsigned, %s>(p, v, %s);\n" % (s, o), "out")
    return ("  unsigned e = 0u;\n"
            "  out[0] = A::compareExchange<unsigned, %s>(p, e, v, %s) ? 1u : 0u;\n"
            % (s, o), "out")


def generate():
    lines = []
    lines.append("// generated by order_scope_dispatch.py -- do not edit\n")
    lines.append("#define FLAGCX_ILUVATAR_DEVICE_COMPILE 1\n")
    lines.append("#define USE_ILUVATAR_ADAPTOR 1\n")
    lines.append('#include "platform_traits.h"\n\n')
    lines.append("typedef PlatformTraits<IluvatarPlatform>::Atomic A;\n\n")
    for m in range(8):
        for o in range(5):
            for s in range(4):
                b, _ = body(m, o, s)
                lines.append("__global__ void k_m%do%ds%d(unsigned *p, unsigned *out) {\n"
                             % (m, o, s))
                lines.append("  unsigned v = 7u;\n  (void)v; (void)p; (void)out;\n")
                lines.append(b)
                lines.append("}\n\n")
    os.makedirs(OUT, exist_ok=True)
    src = os.path.join(OUT, "order_scope_dispatch.cu")
    with io.open(src, "w", encoding="utf-8") as h:
        h.write("".join(lines))
    return src


def run(cmd):
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    return p.returncode, p.stdout.decode("utf-8", "replace")


SYM = re.compile(r"^_Z8(k_m(\d)o(\d)s(\d))PjS_:[ \t]*(?:;.*)?$")


def parse_isa(path):
    """kernel symbol -> tuple of instruction mnemonics."""
    bodies, cur = {}, None
    with io.open(path, encoding="utf-8", errors="replace") as h:
        for raw in h:
            line = raw.rstrip("\n")
            m = SYM.match(line)
            if m:
                cur = m.group(1)
                bodies[cur] = []
                continue
            if cur is None:
                continue
            st = line.strip()
            if st.startswith(".section") or st.startswith(".text"):
                cur = None
                continue
            if not st or st.startswith(".") or st.startswith(";") or st.startswith("//"):
                continue
            if " = " in st:          # .iluvatar_kernel_code_t metadata, not an instruction
                continue
            tok = st.split()[0]
            if tok.startswith("."):
                continue
            if re.match(r"^[a-z][a-z0-9_]*$", tok):
                bodies[cur].append(tok)
    return bodies


ATOM = re.compile(r"(atomicrmw|atomic load|atomic store|load atomic|store atomic)")


def parse_ir_orders(path):
    """kernel -> the atomic IR line, for the contrast table."""
    out, cur = {}, None
    with io.open(path, encoding="utf-8", errors="replace") as h:
        for raw in h:
            line = raw.rstrip("\n")
            m = re.match(r"^define .*@_Z8(k_m\d+o\d+s\d+)PjS_\(", line)
            if m:
                cur = m.group(1)
                out[cur] = None
                continue
            if cur and out[cur] is None and re.search(r"atomicrmw|load atomic|store atomic", line):
                out[cur] = line.strip()
            if cur and line == "}":
                cur = None
    return out


def main():
    src = generate()
    print("[gen] %s" % src)

    rc, log = run([CLANG] + BASE + ["-S", "--cuda-device-only"] + DEFS + INC +
                  [src, "-o", os.path.join(OUT, "order_scope_dispatch.s")])
    print("[isa] clang rc=%d" % rc)
    if rc != 0:
        print(log[:4000])
        return 1

    rc2, log2 = run([CLANG] + BASE + ["-emit-llvm", "-S", "--cuda-device-only"] + DEFS + INC +
                    [src, "-o", os.path.join(OUT, "order_scope_dispatch.ll")])
    print("[ir ] clang rc=%d" % rc2)
    if rc2 != 0:
        print(log2[:2000])

    isa = parse_isa(os.path.join(OUT, "order_scope_dispatch.s"))
    print("[isa] kernels found: %d (expect 160)" % len(isa))
    if len(isa) != 160:
        missing = ["k_m%do%ds%d" % (m, o, s)
                   for m in range(8) for o in range(5) for s in range(4)
                   if ("k_m%do%ds%d" % (m, o, s)) not in isa]
        print("       missing: %s" % missing[:12])

    # group per member
    print()
    print("=== per-member grouping (mnemonic sequence) ===")
    print("%-4s %-16s %5s  %s" % ("m", "member", "groups", "verdict"))
    total_groups = 0
    ok = True
    expect = {0: 1, 1: 2, 2: 1, 3: 1, 4: 1, 5: 1, 6: 1, 7: 1}
    for m in range(8):
        groups = {}
        for o in range(5):
            for s in range(4):
                k = "k_m%do%ds%d" % (m, o, s)
                fp = tuple(isa.get(k, ()))
                groups.setdefault(fp, []).append((o, s))
        n = len(groups)
        total_groups += n
        good = (n == expect[m])
        ok = ok and good
        wbinv = sum(1 for o in range(5) for s in range(4)
                    if "ml_lsa_wbinv" in isa.get("k_m%do%ds%d" % (m, o, s), ()))
        print("%-4d %-16s %5d  %s (expect %d)"
              % (m, MEMBERS[m], n, "OK" if good else "MISMATCH", expect[m]))
        print("PROBE|order-scope-dispatch|%s|combos=20|distinct=%d|wbinv=%d|%s"
              % (MEMBERS[m], n, wbinv, "OK" if good else "MISMATCH"))
        if not good or n > 1:
            for fp, members in groups.items():
                tags = ["%s/%s" % (ORDERS[o], SCOPES[s]) for o, s in members]
                print("        group(%2d): %s" % (len(members), ", ".join(tags[:6]) +
                                                  (" ..." if len(tags) > 6 else "")))
                print("                   %s" % (" ".join(fp[:14]) +
                                                 (" ..." if len(fp) > 14 else "")))
    print()
    print("=== totals ===")
    print("distinct groups over all 160 kernels: %d (prediction: 9)" % total_groups)
    holds = (total_groups == 9 and ok)
    print("PREDICTION %s" % ("HOLDS" if holds else "FAILS"))
    print("PROBE|order-scope-dispatch|TOTAL|kernels=%d|distinct=%d|"
          "prediction=9|%s" % (len(isa), total_groups,
                               "HOLDS" if holds else "FAILS"))

    # the headline contrast: IR keeps five tags, ISA collapses them
    ir = parse_ir_orders(os.path.join(OUT, "order_scope_dispatch.ll"))
    print()
    print("=== IR contrast: fetchAdd, System scope, five orders ===")
    for o in range(5):
        k = "k_m2o%ds0" % o
        line = ir.get(k)
        print("  %-8s %s" % (ORDERS[o], line if line else "(no atomic line)"))
    print()
    print("=== ISA contrast: fetchAdd, System scope, five orders ===")
    for o in range(5):
        k = "k_m2o%ds0" % o
        print("  %-8s %s" % (ORDERS[o], " ".join(isa.get(k, ())[:12])))

    with io.open(os.path.join(OUT, "order_scope_dispatch.summary.txt"), "w", encoding="utf-8") as h:
        h.write("order/scope dispatch report\nkernels=%d groups=%d prediction_holds=%s\n"
                % (len(isa), total_groups, total_groups == 9 and ok))
    return 0 if (total_groups == 9 and ok) else 2


if __name__ == "__main__":
    sys.exit(main())
